def genome_text(rows=None) -> str:
    body = [
        "# This data file generated by 23andMe at: Mon Nov 02 00:00:00 2026",
        "#",
        "# Synthetic GeneMeal fixture. Not a real customer file.",
        "# We are using reference human assembly build 37 (also known as Annotation Release 104).",
        "#",
        "# rsid\tchromosome\tposition\tgenotype",
    ]
    for row in rows or ROWS:
        body.append("\t".join(row))
    return "\n".join(body) + "\n"


def make_zip(members: dict[str, bytes | str], *, filename_hint: str = "genome_Synthetic.zip") -> tuple[str, bytes]:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as archive:
        for name, payload in members.items():
            raw = payload if isinstance(payload, bytes) else payload.encode("utf-8")
            archive.writestr(name, raw)
    return filename_hint, buf.getvalue()


def genome_zip() -> tuple[str, bytes]:
    return make_zip(
        {
            "__MACOSX/._genome_Synthetic_Full.txt": b"\x00\x05not-text",
            "genome_Synthetic_Full.txt": genome_text(),
        }
    )
